def load_arb(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def dump_arb(path: Path, data: dict) -> None:
    # Preserve trailing newline; indent like flutter gen-l10n style (2 spaces).
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    en = load_arb(ROOT / "app_en.arb")
    en_keys = [k for k in en if not k.startswith("@") and k != "@@locale"]
    locales = ["de", "fr", "it", "ja", "ko", "zh"]
    for loc in locales:
        path = ROOT / f"app_{loc}.arb"
        data = load_arb(path)
        added = 0
        for key in en_keys:
            if key in data:
                continue
            if key not in T or loc not in T[key]:
                raise SystemExit(f"Missing translation for {key} / {loc}")
            data[key] = T[key][loc]
            meta_key = f"@{key}"
            if meta_key in en and meta_key not in data:
                data[meta_key] = en[meta_key]
            added += 1
        dump_arb(path, data)
        print(f"{loc}: added {added} keys (now {sum(1 for k in data if not k.startswith('@'))} message keys)")


if __name__ == "__main__":
    main()
