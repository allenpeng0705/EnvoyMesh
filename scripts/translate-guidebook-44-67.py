for _old, _new in HEADING_FIXES.items():
    if _old in BODY:
        BODY[_new] = BODY.pop(_old)



def apply() -> tuple[int, int, list[str]]:
    lines = ZH.read_text(encoding="utf-8").splitlines(keepends=True)
    translated = 0
    skipped: list[str] = []
    seen_headings: set[str] = set()

    i = 0
    while i < len(lines):
        raw = lines[i].rstrip("\n")
        if raw in HEADING_FIXES:
            lines[i] = HEADING_FIXES[raw] + "\n"
        heading = lines[i].rstrip("\n")
        seen_headings.add(heading)

        if heading.startswith("#### ") and heading in BODY:
            j = i + 1
            if j < len(lines) and lines[j].strip() == "":
                j += 1
            if j < len(lines) and not lines[j].startswith("#") and lines[j].strip() != "---":
                old_body = lines[j].rstrip("\n")
                new_body = BODY[heading]
                if old_body != new_body:
                    lines[j] = new_body + "\n"
                    translated += 1
                i = j
        i += 1

    for h in BODY:
        if h not in seen_headings:
            skipped.append(h)

    ZH.write_text("".join(lines), encoding="utf-8")
    return translated, len(BODY), skipped


