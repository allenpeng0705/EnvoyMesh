def load_message_keys(en_data: dict) -> list[str]:
    return [k for k in en_data if not k.startswith("@")]


def write_arb(locale: str, messages: dict[str, str]) -> None:
    out = {"@@locale": locale, **messages}
    path = L10N / f"app_{locale}.arb"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write("\n")


def main() -> int:
    with open(EN_PATH, encoding="utf-8") as f:
        en = json.load(f)
    en_keys = load_message_keys(en)
    en_set = set(en_keys)

    for locale, trans in TRANSLATIONS.items():
        missing = en_set - set(trans)
        extra = set(trans) - en_set
        if missing:
            print(f"ERROR {locale}: missing {len(missing)} keys: {sorted(missing)[:5]}...", file=sys.stderr)
            return 1
        if extra:
            print(f"WARN {locale}: extra keys ignored: {len(extra)}", file=sys.stderr)
        ordered = {k: trans[k] for k in en_keys}
        write_arb(locale, ordered)
        print(f"Wrote app_{locale}.arb — {len(ordered)} keys")

    print(f"\nEnglish reference: {len(en_keys)} keys")
    for locale in TRANSLATIONS:
        trans_keys = set(TRANSLATIONS[locale])
        match = trans_keys == en_set
        print(f"  {locale}: {len(trans_keys)} keys {'✓' if match else '✗ MISMATCH'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
